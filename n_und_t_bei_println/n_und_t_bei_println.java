// Diese Klasse zeigt, wie Escape-Sequenzen in Konsolenausgaben funktionieren.
public class n_und_t_bei_println {
	// Die main-Methode startet das Programm und führt die Ausgaben nacheinander aus.
	public static void main(String[] args) {
		// "\n" erzeugt vor dem Text einen Zeilenumbruch.
		System.out.print("\n Hello, World!");
        // "\t" erzeugt vor dem Text einen Tabulator (Einrückung).
        System.out.print("\t Hello, World!");
	}
}
